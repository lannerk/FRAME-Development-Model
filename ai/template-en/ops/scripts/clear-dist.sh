#!/usr/bin/env bash
# clear-dist: remove **build-output directories** (dist, build, out, ...) across the repo -- **only what git ignores**. For the Requester.
# Dependencies and build-temp directories (node_modules, caches) are clear-build. Two scripts because **build output is
# sometimes worth keeping** (the Requester, 2026-10-01: "use a separate clear-dist script, because sometimes I want to keep the build output").
# The root dist/ holds deliverables by the dist/README.md convention: **only its contents go; README.md stays.**
# Usage (from anywhere inside the repo): bash ops/scripts/clear-dist.sh        list first, ask once, then delete
#                                        bash ops/scripts/clear-dist.sh -y     delete without asking
#       Windows: double-click ops\scripts\clear-dist.bat (same criterion)
# The project has other directory names: add them with CLEAR_DIST_EXTRA="name name" -- do not edit this file (it is FRAME itself; a sync overwrites it).
#
# 【Why this exists】AI sessions install dependencies and produce build output inside the repo; git never takes them,
# yet they stay: every guard that walks the repo walks tens of thousands of extra files (measured: 65% of one
# repo's 25,000 files were git-ignored). AI sessions have no delete permission by default -- so cleaning up
# is a one-click job for the Requester.
# 【One criterion: only what git ignores】A matching name is not enough -- **git itself must say "ignored"**:
# the candidates come straight from git (ls-files --others --ignored --directory); the name is only the second filter.
# For a wholly ignored parent (tmp/, say) git reports just the parent, so nothing inside it becomes a candidate --
# tmp/ is the seats' scratch area, and each seat cleans its own.
# 【Why not plain git clean -X】It deletes **everything** ignored: local config, key files, drafts in tmp/ that a seat has not merged back.
set -u
export GIT_OPTIONAL_LOCKS=0
yes=0; case "${1:-}" in -y|--yes|/y) yes=1;; esac
root="$(git rev-parse --show-toplevel 2>/dev/null)" || { echo "not inside a git repository"; exit 2; }
cd "$root" || exit 2
names=" dist build out .next .output storybook-static ${CLEAR_DIST_EXTRA:-} "
# What the root dist/ holds besides README.md (used both to decide and to check the delete)
rest() { find dist -mindepth 1 -maxdepth 1 ! -name README.md -print 2>/dev/null; }

list=()
while IFS= read -r p; do
  case "$p" in */) ;; *) continue;; esac
  d="${p%/}"; b="${d##*/}"
  case "$names" in *" $b "*) ;; *) continue;; esac
  # Safety net: never touch a directory holding a tracked file (there should be none when git ignores the whole directory, but a wrong delete cannot be undone)
  [ -z "$(git ls-files -- "$d" 2>/dev/null | head -1)" ] || { echo "  . skipped (holds git-tracked files): $d"; continue; }
  # The root dist/: a candidate only when it holds something besides README.md
  if [ "$d" = dist ] && [ -z "$(rest | head -1)" ]; then continue; fi
  list+=("$d")
done < <(git -c core.quotepath=false ls-files --others --ignored --exclude-standard --directory 2>/dev/null)

if [ "${#list[@]}" -eq 0 ]; then echo "CLEAR-DIST-OK (no build output to clean)"; exit 0; fi
echo "These ${#list[@]} directories are ignored by git and named like build output; they can go:"
for d in "${list[@]}"; do if [ "$d" = dist ]; then echo "  dist (contents only; README.md stays)"; else echo "  $d"; fi; done
if [ "$yes" != 1 ]; then
  a=""; read -r -p "Delete them? Type y and press Enter: " a || true
  case "$a" in y|Y) ;; *) echo "Nothing deleted."; exit 0;; esac
fi
fail=0
for d in "${list[@]}"; do
  if [ "$d" = dist ]; then
    rest | while IFS= read -r x; do rm -rf -- "$x" 2>/dev/null; done
    [ -z "$(rest | head -1)" ] || { echo "  x could not delete: $d"; fail=$((fail+1)); }
    continue
  fi
  rm -rf -- "$d" 2>/dev/null
  if [ -e "$d" ]; then echo "  x could not delete: $d"; fail=$((fail+1)); fi
done
[ "$fail" -eq 0 ] || { echo "CLEAR-DIST-FAIL ($fail could not be deleted -- usually no delete permission, or a file is in use)"; exit 1; }
echo "CLEAR-DIST-OK (deleted ${#list[@]} directories; rebuild when you need them)"
